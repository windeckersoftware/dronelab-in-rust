"""Write src/mrac_tables.rs from upstream's MRACControl start-up matrices.

    bench/.venv-pybullet/bin/python crates/compat/tools/gen_mrac_tables.py
"""

from pathlib import Path

import numpy as np
from gym_pybullet_drones.control.MRACControl import MRACControl
from gym_pybullet_drones.utils.enums import DroneModel

OUT = Path(__file__).resolve().parents[1] / "src" / "mrac_tables.rs"


def mat(a):
    rows = ",\n        ".join("[" + ", ".join(repr(float(x)) for x in row) + "]" for row in np.atleast_2d(a))
    return "[\n        " + rows + ",\n    ]"


parts = ["//! Generated by tools/gen_mrac_tables.py from upstream's MRACControl; do not edit.\n",
         "#![allow(clippy::all)]\n", "use dronelab::DroneModel;\n",
         "#[derive(Debug)]\npub struct Tables {\n    pub kx: [[f64; 4]; 12],\n    pub kr: [[f64; 4]; 4],\n    pub kr_ref_gain: [[f64; 12]; 4],\n"
         "    pub am: [[f64; 12]; 12],\n    pub bm: [[f64; 4]; 12],\n    pub p: [[f64; 12]; 12],\n"
         "    pub gamma_x: [[f64; 12]; 12],\n    pub gamma_r: [[f64; 4]; 4],\n}\n"]
names = {DroneModel.CF2X: "CF2X", DroneModel.CF2P: "CF2P", DroneModel.RACE: "RACE"}
for m, name in names.items():
    c = MRACControl(drone_model=m)
    parts.append(f"pub static {name}: Tables = Tables {{\n    kx: {mat(c.Kx)},\n    kr: {mat(c.Kr)},\n"
                 f"    kr_ref_gain: {mat(c.Kr_ref_gain)},\n    am: {mat(c.Am)},\n    bm: {mat(c.Bm)},\n    p: {mat(c.P)},\n"
                 f"    gamma_x: {mat(c.Gamma_x)},\n    gamma_r: {mat(c.Gamma_r)},\n}};\n")
parts.append("pub fn for_model(m: DroneModel) -> &'static Tables {\n    match m {\n        DroneModel::Cf2x => &CF2X,\n"
             "        DroneModel::Cf2p => &CF2P,\n        DroneModel::Race => &RACE,\n    }\n}\n")
OUT.write_text("\n".join(parts))
print("wrote", OUT, OUT.stat().st_size // 1024, "KiB")
